// @vitest-environment node
import {mkdir, mkdtemp, readdir, rm, writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {resolve} from 'node:path';
import {createConsola} from 'consola';
import {removeStaleNodeServer} from '@dota/vite/deployment/server';

const logger = createConsola({level: -999});

describe('removeStaleNodeServer', () => {
  let root: string;

  beforeEach(async () => {
    root = await mkdtemp(resolve(tmpdir(), 'dota-stale-server-'));
  });

  afterEach(async () => {
    await rm(root, {recursive: true, force: true});
  });

  it('removes a server directory generated by an earlier build', async () => {
    await mkdir(resolve(root, 'dist-server'));
    await writeFile(resolve(root, 'dist-server/server.mjs'), '// Generated by @ayu-sh-kr/dota-ssr on every build; edits are overwritten.\n');

    await removeStaleNodeServer(root, undefined, logger);

    expect(await readdir(root)).toEqual([]);
  });

  it('keeps a directory the plugin did not generate', async () => {
    await mkdir(resolve(root, 'server'));
    await writeFile(resolve(root, 'server/server.mjs'), 'console.log("mine");\n');

    await removeStaleNodeServer(root, 'server', logger);

    expect(await readdir(resolve(root, 'server'))).toEqual(['server.mjs']);
  });
});
