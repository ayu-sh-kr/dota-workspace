import {copyFile, mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import {basename, dirname, relative, resolve} from 'node:path';
import type {ConsolaInstance} from 'consola';
import {parseVercelConfig, readVercelConfigSource} from '../vercel-config';
import type {DotaServerTarget, ServerDeployment} from '../ssr/types';
import {writeManagedRedirects} from './redirects';
import {
  basePrefix,
  isVercelCatchAll,
  redirectsCatchAlls,
  shellRoutePaths,
  staticPathsShadowedBy,
  toRedirectsSource,
  toVercelSource,
  wildcardRoutePatterns,
  withSlashForms
} from './route-rules';

/** Query parameter carrying the original path through a Vercel rewrite to the function. */
const VERCEL_PATH_PARAMETER = '__dota_path';
/** URL of the generated Vercel function; rewrites with this destination are owned by Dota SSR. */
const VERCEL_FUNCTION_URL = '/api/dota-ssr';
const GENERATED_NOTICE = '// Generated by @ayu-sh-kr/dota-ssr on every build; edits are overwritten.';
/** Most include and exclude rules Cloudflare Pages accepts in `_routes.json`, counted together. */
const CLOUDFLARE_ROUTE_RULE_LIMIT = 100;
/** Clean application shell that declared browser-rendered paths are answered with. */
const SHELL_FILE = 'dota-shell.html';
/** Page static hosts serve, with status 404, for paths nothing else answers. */
const NOT_FOUND_FILE = '404.html';
/** Appended to a generated `404.html`, so a later build replaces it but never an authored one. */
const SHELL_MARKER = '<!-- Generated by @ayu-sh-kr/dota-ssr: application shell -->';
/** Block of `_redirects` holding the shell rewrites for browser-rendered routes. */
const SSR_REDIRECTS_OWNER = 'dota-ssr';

/**
 * Targets whose server sees the request path as sent, so it can redirect one slash form to the
 * other. Vercel rewrites hand the function the route path instead, where a redirect would loop.
 */
export const SLASH_AWARE_TARGETS: ReadonlySet<DotaServerTarget> = new Set(['node', 'netlify', 'cloudflare-pages']);

/**
 * Writes the files a platform needs to run the server bundle for `ssr` routes, while static
 * files and browser-rendered routes stay with the platform's static hosting. Prerendered pages
 * stay static on every target, and unless `notFound` is `false` undeclared paths answer 404.
 * @param target Deployment target.
 * @param deployment Built bundle, route lists, shell, and resolved plugin options.
 * @param logger Build logger for progress and warnings.
 */
export async function prepareServerDeployment(target: DotaServerTarget, deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  switch (target) {
    case 'node':
      return prepareNode(deployment, logger);
    case 'vercel':
      return prepareVercel(deployment, logger);
    case 'netlify':
      return prepareNetlify(deployment, logger);
    case 'cloudflare-pages':
      return prepareCloudflarePages(deployment, logger);
    case 'github-pages':
      logger.warn(`GitHub Pages only serves static files; ${deployment.routes.join(', ')} will render in the browser`);
      return;
  }
}

/**
 * Removes the Node server from an earlier build before this one writes its own, as Vite's
 * `emptyOutDir` does for client output, so a server built for other assets never outlives them.
 * Only a directory whose `server.mjs` carries the generated notice is removed.
 * @param root Project root that `serverOutDir` is resolved against.
 * @param serverOutDir Configured Node server directory, `dist-server` by default.
 * @param logger Build logger for progress and warnings.
 */
export async function removeStaleNodeServer(root: string, serverOutDir: string | undefined, logger: ConsolaInstance): Promise<void> {
  const directory = resolve(root, serverOutDir ?? 'dist-server');
  const entry = await readFile(resolve(directory, 'server.mjs'), 'utf8').catch(() => undefined);
  if (!entry?.startsWith(GENERATED_NOTICE)) return;
  await rm(directory, {recursive: true, force: true});
  logger.debug(`Removed previous Node server ${relative(root, directory)}`);
}

/**
 * `node <serverOutDir>/server.mjs` serves the client directory, `ssr` routes, and the
 * SPA fallback on `PORT` (default 3000), via `createNodeServer`. The fallback is the clean
 * built shell, since SSG may have replaced `index.html` with the prerendered home page.
 * @param deployment Built bundle, shell, output paths, and `serverOutDir`/`notFound` options.
 * @param logger Build logger for progress and warnings.
 */
async function prepareNode(deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const {root, outputDirectory, bundleFile, shell, options} = deployment;
  const directory = resolve(root, options.serverOutDir ?? 'dist-server');
  const knownPathOption = options.notFound === false ? '' : ', isKnownPath: handler.isKnownPath';
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'index.mjs'));
  await writeFile(resolve(directory, 'shell.html'), shell, 'utf8');
  const clientDirectory = relative(directory, outputDirectory).replaceAll('\\', '/') || '.';
  await writeFile(resolve(directory, 'server.mjs'), `${GENERATED_NOTICE}
import {fileURLToPath} from 'node:url';
import {createNodeServer, handler} from './index.mjs';

const clientDirectory = fileURLToPath(new URL(${JSON.stringify(`${clientDirectory}/`)}, import.meta.url));
const fallback = fileURLToPath(new URL('./shell.html', import.meta.url));
const port = Number(process.env.PORT ?? 3000);
createNodeServer({handler, clientDirectory, fallback${knownPathOption}}).listen(port);
`, 'utf8');
  logger.success(`Node server written to ${relative(root, directory)}; start it with \`node ${relative(root, directory)}/server.mjs\``);
}

/**
 * Vercel: `api/dota-ssr.mjs` beside `vercel.json`, with one rewrite per `ssr` route ahead of
 * authored rewrites (the path travels in a query parameter); files win over rewrites, so
 * prerendered pages need no exclusion. The function sees the route path, so a slash policy
 * becomes one permanent redirect per route; with `notFound`, browser routes rewrite to the shell.
 * @param deployment Built bundle, route lists, shell, and Vercel/slash/`notFound` options.
 * @param logger Build logger for progress and warnings.
 */
async function prepareVercel(deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const {root, outputDirectory, bundleFile, routes, clientRoutes, staticRoutes, shell, options} = deployment;
  if (routes.includes('/')) {
    logger.warn('Vercel serves the built index.html before rewrites, so "/" is served as the client shell rather than server-rendered');
  }
  const configured = options.vercelConfigFile;
  const source = await readVercelConfigSource(root, configured)
    .catch(() => ({file: resolve(root, configured ?? 'vercel.json'), text: '{}\n'}));
  const config = parseVercelConfig(source.text, source.file);
  const rewrites = config.rewrites === undefined ? [] : config.rewrites;
  if (!Array.isArray(rewrites)) throw new Error(`Vercel rewrites must be an array: ${source.file}`);

  const redirects = config.redirects === undefined ? [] : config.redirects;
  if (!Array.isArray(redirects)) throw new Error(`Vercel redirects must be an array: ${source.file}`);

  const sources = routes.map(toVercelSource);
  const canonical = (path: string) => options.trailingSlash && path !== '/' ? `${path}/` : path;
  const serverRewrites = sources.map((path) => ({
    source: canonical(path),
    destination: `${VERCEL_FUNCTION_URL}?${VERCEL_PATH_PARAMETER}=${canonical(path)}`
  }));
  const notFound = options.notFound !== false;
  const shellPaths = notFound ? withSlashForms(shellRoutePaths(clientRoutes, staticRoutes).map(toVercelSource)) : [];
  const shellRewrites = shellPaths.map((path) => ({source: path, destination: `/${SHELL_FILE}`}));
  const authored = rewrites.filter((rewrite) => {
    const destination = entryField(rewrite, 'destination') ?? '';
    return !destination.startsWith(VERCEL_FUNCTION_URL) && destination !== `/${SHELL_FILE}`;
  });
  config.rewrites = [...serverRewrites, ...shellRewrites, ...authored];

  // A redirect between the two slash forms of an `ssr` route is generated; owning both directions
  // means switching or dropping the policy leaves nothing stale, and authored redirects are kept.
  const owned = new Set(withSlashForms(sources));
  const isSlashRedirect = (redirect: unknown) => {
    const from = entryField(redirect, 'source');
    const to = entryField(redirect, 'destination');
    return from !== undefined && to !== undefined && owned.has(from) && (to === `${from}/` || from === `${to}/`);
  };
  const slashRedirects = options.trailingSlash === undefined ? [] : sources
    .filter((path) => path !== '/')
    .map((path) => ({
      source: options.trailingSlash ? path : `${path}/`,
      destination: canonical(path),
      permanent: true
    }));
  const keptRedirects = redirects.filter((redirect) => !isSlashRedirect(redirect));
  if (slashRedirects.length || keptRedirects.length !== redirects.length) {
    config.redirects = [...keptRedirects, ...slashRedirects];
  }

  if (notFound) {
    await writeShellFiles(outputDirectory, shell, logger);
    const catchAlls = authored.map((rewrite) => entryField(rewrite, 'source') ?? '').filter(isVercelCatchAll);
    warnCatchAlls(catchAlls, source.file, logger);
  }
  const text = `${JSON.stringify(config, null, 2)}\n`;
  if (text !== source.text) await writeFile(source.file, text, 'utf8');

  const apiDirectory = resolve(dirname(source.file), 'api');
  await mkdir(resolve(apiDirectory, '_dota-ssr'), {recursive: true});
  await copyFile(bundleFile, resolve(apiDirectory, '_dota-ssr', 'index.mjs'));
  await writeFile(resolve(apiDirectory, 'dota-ssr.mjs'), `${GENERATED_NOTICE}
import {handler} from './_dota-ssr/index.mjs';

async function render(request) {
  const url = new URL(request.url);
  url.pathname = url.searchParams.get(${JSON.stringify(VERCEL_PATH_PARAMETER)}) ?? url.pathname;
  url.searchParams.delete(${JSON.stringify(VERCEL_PATH_PARAMETER)});
  return (await handler(new Request(url, request))) ?? new Response('Not found', {status: 404});
}

export const GET = render;
export const HEAD = render;
`, 'utf8');
  logger.success(`Vercel function written to ${relative(root, apiDirectory)}/dota-ssr.mjs with ${routes.length} rewrite${routes.length === 1 ? '' : 's'}`);
}

/**
 * Netlify: a Functions API v2 function in `.netlify/v1/functions/dota-ssr/` whose `config.path`
 * claims only `ssr` routes. Functions win over files, so prerendered pages those routes match go
 * into `config.excludedPath`. With `notFound`, browser routes rewrite to the shell in a managed
 * `_redirects` block (files still win) and Netlify serves `404.html` for everything else.
 * @param deployment Built bundle, route lists, shell, base, and slash/`notFound` options.
 * @param logger Build logger for progress and warnings.
 */
async function prepareNetlify(deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const {root, outputDirectory, bundleFile, routes, clientRoutes, staticRoutes, shell, base, options} = deployment;
  const directory = resolve(root, '.netlify', 'v1', 'functions', 'dota-ssr');
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'server.mjs'));
  const prefix = basePrefix(base);
  const path = [...new Set(serverRouteForms(routes, options.trailingSlash).map((route) => `${prefix}${route}`))];
  const excludedPath = staticPathsShadowedBy(routes, staticRoutes, prefix);
  await writeFile(resolve(directory, 'dota-ssr.mjs'), `${GENERATED_NOTICE}
import {handler} from './server.mjs';

export default async (request) => (await handler(request)) ?? new Response('Not found', {status: 404});

export const config = ${JSON.stringify(excludedPath.length ? {path, excludedPath} : {path})};
`, 'utf8');
  if (options.notFound !== false) {
    const shellPaths = withSlashForms(shellRoutePaths(clientRoutes, staticRoutes));
    const rules = shellPaths.map((route) => `${prefix}${toRedirectsSource(route)} ${prefix}/${SHELL_FILE} 200`);
    const authoredRules = await writeManagedRedirects(outputDirectory, SSR_REDIRECTS_OWNER, rules);
    await writeShellFiles(outputDirectory, shell, logger);
    warnCatchAlls(redirectsCatchAlls(authoredRules, prefix), resolve(outputDirectory, '_redirects'), logger);
  }
  logger.success(`Netlify function written to ${relative(root, directory)}`);
}

/**
 * Cloudflare Pages: an advanced-mode `_worker.js/` plus `_routes.json`, whose collapsed wildcards
 * send only declared routes to the worker and exclude prerendered pages. With `notFound`, browser
 * routes reach the worker for the shell and `404.html` answers the rest; rules past the platform
 * limit are written with a warning. A `wrangler.toml` enabling `nodejs_compat` is added if missing.
 * @param deployment Built bundle, route lists, shell, base, and slash/`notFound`/cache options.
 * @param logger Build logger for progress and warnings.
 */
async function prepareCloudflarePages(deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const {root, outputDirectory, bundleFile, routes, clientRoutes, staticRoutes, shell, base, options} = deployment;
  const prefix = basePrefix(base);
  const notFound = options.notFound !== false;
  const shellPaths = notFound ? shellRoutePaths(clientRoutes, staticRoutes) : [];
  const serverForms = serverRouteForms(routes, options.trailingSlash);
  const include = wildcardRoutePatterns([...serverForms, ...withSlashForms(shellPaths)], prefix);
  const exclude = staticPathsShadowedBy([...routes, ...shellPaths], staticRoutes, prefix);
  const ruleCount = include.length + exclude.length;
  if (ruleCount > CLOUDFLARE_ROUTE_RULE_LIMIT) {
    logger.warn(`_routes.json has ${ruleCount} rules (${include.length} include, ${exclude.length} exclude), `
      + `but Cloudflare Pages accepts ${CLOUDFLARE_ROUTE_RULE_LIMIT}; the deployment will be rejected until routes `
      + 'are merged, fewer pages under them are prerendered, or notFound: false stops routing browser routes');
  }
  const directory = resolve(outputDirectory, '_worker.js');
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'server.js'));
  await writeFile(resolve(directory, 'index.js'), `${GENERATED_NOTICE}
import {handler} from './server.js';

${notFound ? cloudflareShellRender(`${prefix}/${SHELL_FILE.replace(/\.html$/, '')}`) : CLOUDFLARE_RENDER}

${options.cacheControl ? CLOUDFLARE_CACHED_EXPORT : CLOUDFLARE_EXPORT}
`, 'utf8');
  if (notFound) await writeShellFiles(outputDirectory, shell, logger);
  const routesJson = JSON.stringify({version: 1, include, exclude}, null, 2);
  await writeFile(resolve(outputDirectory, '_routes.json'), `${routesJson}\n`, 'utf8');

  const wranglerFile = resolve(root, 'wrangler.toml');
  const wrangler = await readFile(wranglerFile, 'utf8').catch(() => undefined);
  if (wrangler === undefined) {
    const name = await projectName(root);
    await writeFile(wranglerFile, [
      '# Generated by @ayu-sh-kr/dota-ssr: server rendering needs the nodejs_compat flag.',
      `name = ${JSON.stringify(name)}`,
      `pages_build_output_dir = ${JSON.stringify(relative(root, outputDirectory).replaceAll('\\', '/') || '.')}`,
      `compatibility_date = ${JSON.stringify(new Date().toISOString().slice(0, 10))}`,
      'compatibility_flags = ["nodejs_compat"]',
      ''
    ].join('\n'), 'utf8');
  } else if (!wrangler.includes('nodejs_compat')) {
    logger.warn(`${relative(root, wranglerFile)} must enable compatibility_flags = ["nodejs_compat"] for server rendering`);
  }
  logger.success(`Cloudflare Pages worker written to ${relative(root, directory)}`);
}

/** Worker request handling with `notFound: false`: renders `ssr` routes, else serves the asset. */
const CLOUDFLARE_RENDER = `async function render(request, env) {
  return (await handler(request)) ?? env.ASSETS.fetch(request);
}`;

/**
 * Worker request handling: renders `ssr` routes; answers other declared paths with the shell
 * (or the file at that path); and answers undeclared paths with the asset host's response,
 * whose HTML fallback becomes a 404.
 * @param shellPath URL path of the shell as Cloudflare serves it, without `.html`.
 */
function cloudflareShellRender(shellPath: string): string {
  return `async function render(request, env) {
  const response = await handler(request);
  if (response) return response;
  const asset = await env.ASSETS.fetch(request);
  const known = await handler.isKnownPath(new URL(request.url).pathname);
  if (known) return asset.status === 404 ? env.ASSETS.fetch(new URL(${JSON.stringify(shellPath)}, request.url)) : asset;
  if (asset.status !== 200 || !asset.headers.get('content-type')?.includes('text/html')) return asset;
  return new Response(asset.body, {status: 404, headers: asset.headers});
}`;
}

/** Worker entry without caching: every request is rendered. */
const CLOUDFLARE_EXPORT = `export default {
  fetch: render
};`;

/**
 * Worker entry with the Cache API in front: a cached page is answered without rendering,
 * and a 200 page carrying `Cache-Control` is stored for later requests.
 */
const CLOUDFLARE_CACHED_EXPORT = `export default {
  async fetch(request, env, context) {
    const cache = request.method === 'GET' ? caches.default : undefined;
    const cached = await cache?.match(request);
    if (cached) return cached;
    const response = await render(request, env);
    if (cache && response.status === 200 && response.headers.has('cache-control')) {
      context.waitUntil(cache.put(request, response.clone()));
    }
    return response;
  }
};`;

/**
 * The `ssr` paths a host must route to the server: with a slash policy, both forms of each route,
 * so the server can redirect the other one; without, only the declared form, as before.
 * @param routes Router-style `ssr` paths.
 * @param trailingSlash Resolved slash policy, or `undefined` when none is set.
 */
function serverRouteForms(routes: readonly string[], trailingSlash: boolean | undefined): readonly string[] {
  return trailingSlash === undefined ? routes : withSlashForms(routes);
}

/**
 * Reads a string field of an authored `vercel.json` rewrite or redirect, whose entries are not
 * validated, so foreign or malformed entries are kept instead of failing the build.
 * @param entry Rewrite or redirect as parsed from JSON.
 * @param key Field to read, such as `source` or `destination`.
 * @returns The value when it is a string, else `undefined`.
 */
function entryField(entry: unknown, key: 'source' | 'destination'): string | undefined {
  const value = (entry as Record<string, unknown> | null)?.[key];
  return typeof value === 'string' ? value : undefined;
}

/**
 * Writes the clean shell (captured before SSG replaced `index.html`) as `dota-shell.html`, and as
 * `404.html` unless the output already holds an authored one, which is kept.
 * @param outputDirectory Absolute client output directory.
 * @param shell Built shell from the client build.
 * @param logger Build logger for progress and warnings.
 */
async function writeShellFiles(outputDirectory: string, shell: string, logger: ConsolaInstance): Promise<void> {
  await writeFile(resolve(outputDirectory, SHELL_FILE), shell, 'utf8');
  const notFoundFile = resolve(outputDirectory, NOT_FOUND_FILE);
  const existing = await readFile(notFoundFile, 'utf8').catch(() => undefined);
  if (existing !== undefined && !existing.endsWith(SHELL_MARKER)) {
    logger.debug(`Keeping the authored ${NOT_FOUND_FILE}`);
    return;
  }
  await writeFile(notFoundFile, `${shell.trimEnd()}\n${SHELL_MARKER}`, 'utf8');
}

/**
 * Warns about authored catch-all rules, which answer unknown paths with 200 before `404.html` can.
 * Declared browser routes are rewritten to the shell already, so these rules can be removed.
 * @param rules Catch-all rules as written.
 * @param file File holding them, named in the warning.
 * @param logger Build logger for progress and warnings.
 */
function warnCatchAlls(rules: readonly string[], file: string, logger: ConsolaInstance): void {
  if (rules.length === 0) return;
  logger.warn(`${file} has a catch-all (${rules.join(', ')}) that answers unknown paths with 200; `
    + 'remove it for 404s, since declared routes already rewrite to the application shell');
}

/** Worker name for `wrangler.toml`: the package name, made DNS-safe, else the directory name. */
async function projectName(root: string): Promise<string> {
  const manifest = await readFile(resolve(root, 'package.json'), 'utf8').then((text) => JSON.parse(text) as {name?: string}).catch(() => undefined);
  const name = (manifest?.name ?? basename(root)).replace(/^@[^/]+\//, '').toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
  return name || 'dota-app';
}
