import {copyFile, mkdir, readFile, rm, writeFile} from 'node:fs/promises';
import {basename, dirname, relative, resolve} from 'node:path';
import type {ConsolaInstance} from 'consola';
import {parseVercelConfig, readVercelConfigSource} from '../vercel-config';
import type {DotaServerTarget, ServerDeployment} from '../ssr/types';
import {staticPathsShadowedBy, wildcardRoutePatterns} from './route-rules';

/** Query parameter carrying the original path through a Vercel rewrite to the function. */
const VERCEL_PATH_PARAMETER = '__dota_path';
/** URL of the generated Vercel function; rewrites with this destination are owned by Dota SSR. */
const VERCEL_FUNCTION_URL = '/api/dota-ssr';
const GENERATED_NOTICE = '// Generated by @ayu-sh-kr/dota-ssr on every build; edits are overwritten.';
/** Most include and exclude rules Cloudflare Pages accepts in `_routes.json`, counted together. */
const CLOUDFLARE_ROUTE_RULE_LIMIT = 100;

/**
 * Writes the files a platform needs to run the server bundle for `ssr` routes, while
 * static files (assets, `ssg` pages) and the SPA fallback (`csr` routes) stay with the
 * platform's static hosting. A prerendered page an `ssr` pattern also matches stays static
 * on every target: Node and Vercel check files before the server, and Netlify and Cloudflare
 * Pages get it as an exclusion.
 * @param target Deployment target.
 * @param deployment Built bundle, routes, and paths.
 */
export async function prepareServerDeployment(target: DotaServerTarget, deployment: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  switch (target) {
    case 'node':
      return prepareNode(deployment, logger);
    case 'vercel':
      return prepareVercel(deployment, logger);
    case 'netlify':
      return prepareNetlify(deployment, logger);
    case 'cloudflare-pages':
      return prepareCloudflarePages(deployment, logger);
    case 'github-pages':
      logger.warn(`GitHub Pages only serves static files; ${deployment.routes.join(', ')} will render in the browser`);
      return;
  }
}

/**
 * Removes the Node server from an earlier build before this one writes its own, as Vite's
 * `emptyOutDir` does for client output, so a server built for other assets never outlives them.
 * Only a directory whose `server.mjs` carries the generated notice is removed.
 * @param root Project root that `serverOutDir` is resolved against.
 * @param serverOutDir Configured Node server directory, `dist-server` by default.
 */
export async function removeStaleNodeServer(root: string, serverOutDir: string | undefined, logger: ConsolaInstance): Promise<void> {
  const directory = resolve(root, serverOutDir ?? 'dist-server');
  const entry = await readFile(resolve(directory, 'server.mjs'), 'utf8').catch(() => undefined);
  if (!entry?.startsWith(GENERATED_NOTICE)) return;
  await rm(directory, {recursive: true, force: true});
  logger.debug(`Removed previous Node server ${relative(root, directory)}`);
}

/**
 * `node <serverOutDir>/server.mjs` serves the client directory, `ssr` routes, and the
 * SPA fallback on `PORT` (default 3000), via `createNodeServer`. The fallback is the clean
 * built shell, since SSG may have replaced `index.html` with the prerendered home page.
 */
async function prepareNode({root, outputDirectory, bundleFile, shell, options}: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const directory = resolve(root, options.serverOutDir ?? 'dist-server');
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'index.mjs'));
  await writeFile(resolve(directory, 'shell.html'), shell, 'utf8');
  const clientDirectory = relative(directory, outputDirectory).replaceAll('\\', '/') || '.';
  await writeFile(resolve(directory, 'server.mjs'), `${GENERATED_NOTICE}
import {fileURLToPath} from 'node:url';
import {createNodeServer, handler} from './index.mjs';

const clientDirectory = fileURLToPath(new URL(${JSON.stringify(`${clientDirectory}/`)}, import.meta.url));
const fallback = fileURLToPath(new URL('./shell.html', import.meta.url));
const port = Number(process.env.PORT ?? 3000);
createNodeServer({handler, clientDirectory, fallback, isKnownPath: handler.isKnownPath}).listen(port);
`, 'utf8');
  logger.success(`Node server written to ${relative(root, directory)}; start it with \`node ${relative(root, directory)}/server.mjs\``);
}

/**
 * Vercel: a function at `api/dota-ssr.mjs` beside `vercel.json` (its bundle in
 * `api/_dota-ssr/`, which Vercel does not expose as a function), and one rewrite per
 * `ssr` route placed ahead of authored rewrites so SPA catch-alls cannot shadow it.
 * The original path travels in a query parameter because a rewrite changes the URL the function sees.
 * Vercel checks the filesystem before rewrites, so prerendered pages need no exclusion; the
 * rewrites go into the same `vercel.json` static generation updated, keeping its redirects.
 */
async function prepareVercel({root, bundleFile, routes, options}: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  if (routes.includes('/')) {
    logger.warn('Vercel serves the built index.html before rewrites, so "/" is served as the client shell rather than server-rendered');
  }
  const configured = options.vercelConfigFile;
  const source = await readVercelConfigSource(root, configured)
    .catch(() => ({file: resolve(root, configured ?? 'vercel.json'), text: '{}\n'}));
  const config = parseVercelConfig(source.text, source.file);
  const rewrites = config.rewrites === undefined ? [] : config.rewrites;
  if (!Array.isArray(rewrites)) throw new Error(`Vercel rewrites must be an array: ${source.file}`);

  const authored = rewrites.filter((rewrite) => !String((rewrite as {destination?: unknown})?.destination ?? '').startsWith(VERCEL_FUNCTION_URL));
  const generated = routes.map((path) => ({source: path, destination: `${VERCEL_FUNCTION_URL}?${VERCEL_PATH_PARAMETER}=${path}`}));
  config.rewrites = [...generated, ...authored];
  const text = `${JSON.stringify(config, null, 2)}\n`;
  if (text !== source.text) await writeFile(source.file, text, 'utf8');

  const apiDirectory = resolve(dirname(source.file), 'api');
  await mkdir(resolve(apiDirectory, '_dota-ssr'), {recursive: true});
  await copyFile(bundleFile, resolve(apiDirectory, '_dota-ssr', 'index.mjs'));
  await writeFile(resolve(apiDirectory, 'dota-ssr.mjs'), `${GENERATED_NOTICE}
import {handler} from './_dota-ssr/index.mjs';

async function render(request) {
  const url = new URL(request.url);
  url.pathname = url.searchParams.get(${JSON.stringify(VERCEL_PATH_PARAMETER)}) ?? url.pathname;
  url.searchParams.delete(${JSON.stringify(VERCEL_PATH_PARAMETER)});
  return (await handler(new Request(url, request))) ?? new Response('Not found', {status: 404});
}

export const GET = render;
export const HEAD = render;
`, 'utf8');
  logger.success(`Vercel function written to ${relative(root, apiDirectory)}/dota-ssr.mjs with ${routes.length} rewrite${routes.length === 1 ? '' : 's'}`);
}

/**
 * Netlify: a Functions API v2 function in `.netlify/v1/functions/dota-ssr/` (the Frameworks
 * API directory Netlify picks up without configuration). Its `config.path` lists only the `ssr`
 * routes, so it takes precedence just for them, including over the shell at `/index.html`.
 * Functions also win over static files, so prerendered pages those routes match are listed in
 * `config.excludedPath`.
 */
async function prepareNetlify({root, bundleFile, routes, staticRoutes, base, options}: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const directory = resolve(root, '.netlify', 'v1', 'functions', 'dota-ssr');
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'server.mjs'));
  const prefix = basePrefix(base);
  const path = [...new Set(withSlashForms(routes, options.trailingSlash).map((route) => `${prefix}${route}`))];
  const excludedPath = staticPathsShadowedBy(routes, staticRoutes, prefix);
  await writeFile(resolve(directory, 'dota-ssr.mjs'), `${GENERATED_NOTICE}
import {handler} from './server.mjs';

export default async (request) => (await handler(request)) ?? new Response('Not found', {status: 404});

export const config = ${JSON.stringify(excludedPath.length ? {path, excludedPath} : {path})};
`, 'utf8');
  logger.success(`Netlify function written to ${relative(root, directory)}`);
}

/**
 * Cloudflare Pages: an advanced-mode `_worker.js/` in the output directory that renders
 * `ssr` routes and hands everything else to the static assets, plus `_routes.json` so
 * only `ssr` paths invoke the worker: overlapping wildcards are collapsed, which Cloudflare
 * requires, and prerendered pages they match are excluded so their snapshots are served.
 * The bundle needs the `nodejs_compat` flag (for `AsyncLocalStorage`), so a `wrangler.toml`
 * enabling it is written when none exists.
 * Rules beyond Cloudflare's limit are still written, with a warning naming the counts.
 */
async function prepareCloudflarePages({root, outputDirectory, bundleFile, routes, staticRoutes, base, options}: ServerDeployment, logger: ConsolaInstance): Promise<void> {
  const prefix = basePrefix(base);
  const include = wildcardRoutePatterns(withSlashForms(routes, options.trailingSlash), prefix);
  const exclude = staticPathsShadowedBy(routes, staticRoutes, prefix);
  if (include.length + exclude.length > CLOUDFLARE_ROUTE_RULE_LIMIT) {
    logger.warn(`_routes.json has ${include.length + exclude.length} rules (${include.length} include, ${exclude.length} exclude), `
      + `but Cloudflare Pages accepts ${CLOUDFLARE_ROUTE_RULE_LIMIT}; the deployment will be rejected until server routes are merged `
      + 'or fewer pages under them are prerendered');
  }
  const directory = resolve(outputDirectory, '_worker.js');
  await rm(directory, {recursive: true, force: true});
  await mkdir(directory, {recursive: true});
  await copyFile(bundleFile, resolve(directory, 'server.js'));
  await writeFile(resolve(directory, 'index.js'), `${GENERATED_NOTICE}
import {handler} from './server.js';

${CLOUDFLARE_RENDER}

${options.cacheControl ? CLOUDFLARE_CACHED_EXPORT : CLOUDFLARE_EXPORT}
`, 'utf8');
  await writeFile(resolve(outputDirectory, '_routes.json'), `${JSON.stringify({version: 1, include, exclude}, null, 2)}\n`, 'utf8');

  const wranglerFile = resolve(root, 'wrangler.toml');
  const wrangler = await readFile(wranglerFile, 'utf8').catch(() => undefined);
  if (wrangler === undefined) {
    const name = await projectName(root);
    await writeFile(wranglerFile, [
      '# Generated by @ayu-sh-kr/dota-ssr: server rendering needs the nodejs_compat flag.',
      `name = ${JSON.stringify(name)}`,
      `pages_build_output_dir = ${JSON.stringify(relative(root, outputDirectory).replaceAll('\\', '/') || '.')}`,
      `compatibility_date = ${JSON.stringify(new Date().toISOString().slice(0, 10))}`,
      'compatibility_flags = ["nodejs_compat"]',
      ''
    ].join('\n'), 'utf8');
  } else if (!wrangler.includes('nodejs_compat')) {
    logger.warn(`${relative(root, wranglerFile)} must enable compatibility_flags = ["nodejs_compat"] for server rendering`);
  }
  logger.success(`Cloudflare Pages worker written to ${relative(root, directory)}`);
}

/**
 * Worker request handling: renders `ssr` routes, else serves the asset. A path under an `ssr`
 * pattern that no route declares gets the asset (the SPA shell) with status 404.
 */
const CLOUDFLARE_RENDER = `async function render(request, env) {
  const response = await handler(request);
  if (response) return response;
  const asset = await env.ASSETS.fetch(request);
  if (!asset.headers.get('content-type')?.includes('text/html') || await handler.isKnownPath(new URL(request.url).pathname)) return asset;
  return new Response(asset.body, {status: 404, headers: asset.headers});
}`;

/** Worker entry without caching: every request is rendered. */
const CLOUDFLARE_EXPORT = `export default {
  fetch: render
};`;

/**
 * Worker entry with the Cache API in front: a cached page is answered without rendering,
 * and a 200 page carrying `Cache-Control` is stored for later requests.
 */
const CLOUDFLARE_CACHED_EXPORT = `export default {
  async fetch(request, env, context) {
    const cache = request.method === 'GET' ? caches.default : undefined;
    const cached = await cache?.match(request);
    if (cached) return cached;
    const response = await render(request, env);
    if (cache && response.status === 200 && response.headers.has('cache-control')) context.waitUntil(cache.put(request, response.clone()));
    return response;
  }
};`;

/**
 * Adds the slash form of each route when a slash policy is set, so the server receives both
 * URL forms and can redirect one to the other. On Cloudflare Pages the forms of routes ending
 * in a dynamic segment collapse back into their wildcard, which already matches both.
 * @param routes Router-style `ssr` paths.
 * @param trailingSlash Slash policy, or `undefined` to route only the declared form.
 */
function withSlashForms(routes: readonly string[], trailingSlash: boolean | undefined): string[] {
  if (trailingSlash === undefined) return [...routes];
  return [...routes, ...routes.filter((route) => route !== '/').map((route) => `${route}/`)];
}

/** Path of the Vite base without its trailing slash, for platform route patterns. */
function basePrefix(base: string): string {
  return new URL(base, 'https://base.invalid').pathname.replace(/\/$/, '');
}

/** Worker name for `wrangler.toml`: the package name, made DNS-safe, else the directory name. */
async function projectName(root: string): Promise<string> {
  const manifest = await readFile(resolve(root, 'package.json'), 'utf8').then((text) => JSON.parse(text) as {name?: string}).catch(() => undefined);
  const name = (manifest?.name ?? basename(root)).replace(/^@[^/]+\//, '').toLowerCase().replace(/[^a-z0-9-]+/g, '-').replace(/^-+|-+$/g, '');
  return name || 'dota-app';
}
